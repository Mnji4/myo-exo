def independent_constraint_rows(matrix: np.ndarray) -> np.ndarray:
    """Select a numerically independent row basis without changing its row space."""
    if matrix.size == 0:
        return np.empty(0, dtype=np.int64)
    _q, triangular, pivots = qr(matrix.T, mode="economic", pivoting=True)
    diagonal = np.abs(np.diag(triangular))
    if diagonal.size == 0 or diagonal[0] == 0.0:
        return np.empty(0, dtype=np.int64)
    tolerance = max(matrix.shape) * np.finfo(matrix.dtype).eps * diagonal[0]
    rank = int(np.count_nonzero(diagonal > tolerance))
    return np.sort(np.asarray(pivots[:rank], dtype=np.int64))


def evolve_activation(
    model: mujoco.MjModel,
    activation: np.ndarray,
    excitation: np.ndarray,
    frame_skip: int,
) -> np.ndarray:
    """Integrate MuJoCo's muscle activation dynamics for one policy frame."""
    value = np.asarray(activation, dtype=np.float64).copy()
    excitation = np.asarray(excitation, dtype=np.float64)
    dynamics = [np.ascontiguousarray(model.actuator_dynprm[i, :3]) for i in range(int(model.na))]
    for _ in range(int(frame_skip)):
        derivative = np.asarray(
            [mujoco.mju_muscleDynamics(excitation[i], value[i], dynamics[i]) for i in range(int(model.na))],
            dtype=np.float64,
        )
        value = np.clip(value + float(model.opt.timestep) * derivative, 0.0, 1.0)
    return value


def activation_trajectory(
    model: mujoco.MjModel,
    activation: np.ndarray,
    excitation: np.ndarray,
    frame_skip: int,
) -> np.ndarray:
    """Return activation after every physics substep in one policy frame."""
    value = np.asarray(activation, dtype=np.float64).copy()
    excitation = np.asarray(excitation, dtype=np.float64)
    dynamics = [
        np.ascontiguousarray(model.actuator_dynprm[i, :3])
        for i in range(int(model.na))
    ]
    values = []
    for _ in range(int(frame_skip)):
        derivative = np.asarray(
            [
                mujoco.mju_muscleDynamics(excitation[i], value[i], dynamics[i])
                for i in range(int(model.na))
            ],
            dtype=np.float64,
        )
        value = np.clip(
            value + float(model.opt.timestep) * derivative, 0.0, 1.0
        )
        values.append(value.copy())
    return np.stack(values)


def excitation_for_target_activation(
    model: mujoco.MjModel,
    current: np.ndarray,
    target: np.ndarray,
    frame_skip: int,
    excitation_low: np.ndarray,
    excitation_high: np.ndarray,
) -> np.ndarray:
    """Invert independent muscle dynamics by monotone bisection."""
    low = np.asarray(excitation_low, dtype=np.float64).copy()
    high = np.asarray(excitation_high, dtype=np.float64).copy()
    for _ in range(24):
        middle = 0.5 * (low + high)
        reached = evolve_activation(model, current, middle, frame_skip)
        low = np.where(reached < target, middle, low)
        high = np.where(reached >= target, middle, high)
    return 0.5 * (low + high)


def active_torque_map(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    qpos: np.ndarray,
    qvel: np.ndarray,
    joint_dofs: np.ndarray,
) -> np.ndarray:
    """Return the six-joint active torque generated by each unit activation."""
    muscle_count = int(model.na)

    def torque_for(activation: np.ndarray) -> np.ndarray:
        data.qpos[:] = qpos
        data.qvel[:] = qvel
        data.act[:] = activation
        data.ctrl[:] = 0.0
        mujoco.mj_forward(model, data)
        return np.asarray(data.qfrc_actuator[joint_dofs], dtype=np.float64).copy()

    zero = np.zeros(muscle_count, dtype=np.float64)
    passive = torque_for(zero)
    columns = []
    for index in range(muscle_count):
        basis = zero.copy()
        basis[index] = 1.0
        columns.append(torque_for(basis) - passive)
    return np.stack(columns, axis=1)


def exo_torque_map(
    model: mujoco.MjModel,
    data: mujoco.MjData,
    qpos: np.ndarray,
    qvel: np.ndarray,
    joint_dofs: np.ndarray,
) -> np.ndarray:
    """Return the six-joint torque generated by each unit Exo control."""
    muscle_count = int(model.na)
    exo_count = min(2, int(model.nu) - muscle_count)
    if exo_count <= 0:
        return np.zeros((len(joint_dofs), 0), dtype=np.float64)

    def torque_for(exo_ctrl: np.ndarray) -> np.ndarray:
        data.qpos[:] = qpos
        data.qvel[:] = qvel
        data.act[:] = 0.0
        data.ctrl[:] = 0.0
        data.ctrl[muscle_count : muscle_count + exo_count] = exo_ctrl
        mujoco.mj_forward(model, data)
        return np.asarray(data.qfrc_actuator[joint_dofs], dtype=np.float64).copy()

    zero = np.zeros(exo_count, dtype=np.float64)
    passive = torque_for(zero)
    columns = []
    for index in range(exo_count):
        basis = zero.copy()
        basis[index] = 1.0
        columns.append(torque_for(basis) - passive)
    return np.stack(columns, axis=1)


def allocate_activation(
    torque_map: np.ndarray,
    target_torque: np.ndarray,
    nominal: np.ndarray,
    lower: np.ndarray,
    upper: np.ndarray,
) -> tuple[np.ndarray, bool, float]:
    """Minimize next activation while preserving the policy's six-joint torque."""
    scale = np.maximum(np.abs(target_torque), 10.0)
    scaled_map = torque_map / scale[:, None]
    scaled_target = target_torque / scale
    rows = independent_constraint_rows(scaled_map)
    constraints = []
    if rows.size:
        constraints.append(
            LinearConstraint(
                scaled_map[rows], scaled_target[rows], scaled_target[rows]
            )
        )
    result = minimize(
        fun=lambda value: 0.5 * float(value @ value),
        x0=np.clip(nominal, lower, upper),
        jac=lambda value: value,
        method="SLSQP",
        bounds=Bounds(lower, upper),
        constraints=constraints,
        options={"ftol": 1.0e-10, "maxiter": 200, "disp": False},
    )
    value = np.clip(np.asarray(result.x, dtype=np.float64), lower, upper)
    error = float(np.linalg.norm(torque_map @ value - target_torque))
    return value, bool(result.success), error


def allocate_activation_and_exo(
    muscle_map: np.ndarray,
    exo_map: np.ndarray,
    target_torque: np.ndarray,
    nominal_activation: np.ndarray,
    nominal_exo: np.ndarray,
    activation_lower: np.ndarray,
    activation_upper: np.ndarray,
    exo_lower: np.ndarray,
    exo_upper: np.ndarray,
    exo_l2_weight: float,
    exo_delta_weight: float,
    previous_exo: np.ndarray,
    prevent_exo_opposition: bool = False,
    opposition_joint_rows: tuple[int, ...] = (0, 3),
) -> tuple[np.ndarray, np.ndarray, bool, float]:
    """Recruit muscles and Exo jointly while prioritizing low human activation."""
    muscle_count = int(muscle_map.shape[1])
    combined_map = np.concatenate((muscle_map, exo_map), axis=1)
    lower = np.concatenate((activation_lower, exo_lower))
    upper = np.concatenate((activation_upper, exo_upper))
    initial = np.concatenate((nominal_activation, nominal_exo))
    scale = np.maximum(np.abs(target_torque), 10.0)
    scaled_map = combined_map / scale[:, None]
    scaled_target = target_torque / scale
    rows = independent_constraint_rows(scaled_map)

    def objective(value: np.ndarray) -> float:
        activation = value[:muscle_count]
        exo = value[muscle_count:]
        return 0.5 * float(
            activation @ activation
            + exo_l2_weight * (exo @ exo)
            + exo_delta_weight * ((exo - previous_exo) @ (exo - previous_exo))
        )

    def gradient(value: np.ndarray) -> np.ndarray:
        activation = value[:muscle_count]
        exo = value[muscle_count:]
        return np.concatenate(
            (
                activation,
                exo_l2_weight * exo + exo_delta_weight * (exo - previous_exo),
            )
        )

    constraints: list[LinearConstraint] = []
    if rows.size:
        constraints.append(
            LinearConstraint(
                scaled_map[rows], scaled_target[rows], scaled_target[rows]
            )
        )
    if prevent_exo_opposition and exo_map.shape[1] > 0:
        opposition_rows = [
            int(row)
            for row in opposition_joint_rows
            if 0 <= int(row) < int(target_torque.size)
        ]
        no_opposition_map = np.zeros(
            (len(opposition_rows), muscle_count + exo_map.shape[1]),
            dtype=np.float64,
        )
        no_opposition_upper = np.zeros(len(opposition_rows), dtype=np.float64)
        for constraint_row, joint_row in enumerate(opposition_rows):
            target = float(target_torque[joint_row])
            direction = 1.0 if target >= 0.0 else -1.0
            no_opposition_map[constraint_row, muscle_count:] = (
                direction * exo_map[joint_row]
            )
            no_opposition_upper[constraint_row] = abs(target)
        constraints.append(
            LinearConstraint(
                no_opposition_map,
                np.zeros(len(opposition_rows), dtype=np.float64),
                no_opposition_upper,
            )
        )

    result = minimize(
        fun=objective,
        x0=np.clip(initial, lower, upper),
        jac=gradient,
        method="SLSQP",
        bounds=Bounds(lower, upper),
        constraints=constraints,
        options={"ftol": 1.0e-10, "maxiter": 200, "disp": False},
    )
    value = np.clip(np.asarray(result.x, dtype=np.float64), lower, upper)
    error = float(np.linalg.norm(combined_map @ value - target_torque))
    return value[:muscle_count], value[muscle_count:], bool(result.success), error


def allocate_hip_pair_replacement(
    muscle_map: np.ndarray,
    exo_map: np.ndarray,
    target_torque: np.ndarray,
    nominal_activation: np.ndarray,
    nominal_exo: np.ndarray,
    activation_lower: np.ndarray,
    activation_upper: np.ndarray,
    exo_lower: np.ndarray,
    exo_upper: np.ndarray,
    replace_indices: np.ndarray,
    prevent_exo_opposition: bool = False,
    opposition_joint_rows: tuple[int, ...] = (0, 3),
) -> tuple[np.ndarray, np.ndarray, bool, float]:
    """Lower only monoarticular hip muscles and replace their torque with Exo."""
    replace_indices = np.asarray(replace_indices, dtype=np.int64)
    fixed_mask = np.ones(muscle_map.shape[1], dtype=bool)
    fixed_mask[replace_indices] = False
    fixed_torque = muscle_map[:, fixed_mask] @ nominal_activation[fixed_mask]
    replacement_map = muscle_map[:, replace_indices]
    combined_map = np.concatenate((replacement_map, exo_map), axis=1)
    residual_target = target_torque - fixed_torque

    activation_high = np.minimum(
        activation_upper[replace_indices], nominal_activation[replace_indices]
    )
    lower = np.concatenate((activation_lower[replace_indices], exo_lower))
    upper = np.concatenate((activation_high, exo_upper))
    initial = np.concatenate(
        (
            np.clip(
                nominal_activation[replace_indices],
                activation_lower[replace_indices],
                activation_high,
            ),
            np.clip(nominal_exo, exo_lower, exo_upper),
        )
    )
    scale = np.maximum(np.abs(residual_target), 10.0)
    scaled_map = combined_map / scale[:, None]
    scaled_target = residual_target / scale
    rows = independent_constraint_rows(scaled_map)
    constraints: list[LinearConstraint] = []
    if rows.size:
        constraints.append(
            LinearConstraint(
                scaled_map[rows], scaled_target[rows], scaled_target[rows]
            )
        )
    if prevent_exo_opposition and exo_map.shape[1] > 0:
        valid_rows = [
            int(row)
            for row in opposition_joint_rows
            if 0 <= int(row) < int(target_torque.size)
        ]
        direction_map = np.zeros(
            (len(valid_rows), combined_map.shape[1]), dtype=np.float64
        )
        direction_upper = np.zeros(len(valid_rows), dtype=np.float64)
        for constraint_row, joint_row in enumerate(valid_rows):
            target = float(target_torque[joint_row])
            direction = 1.0 if target >= 0.0 else -1.0
            direction_map[constraint_row, replace_indices.size :] = (
                direction * exo_map[joint_row]
            )
            direction_upper[constraint_row] = abs(target)
        constraints.append(
            LinearConstraint(
                direction_map,
                np.zeros(len(valid_rows), dtype=np.float64),
                direction_upper,
            )
        )

    muscle_variables = int(replace_indices.size)
    result = minimize(
        fun=lambda value: 0.5
        * float(
            value[:muscle_variables] @ value[:muscle_variables]
            + 1.0e-8
            * value[muscle_variables:] @ value[muscle_variables:]
        ),
        x0=np.clip(initial, lower, upper),
        method="SLSQP",
        bounds=Bounds(lower, upper),
        constraints=constraints,
        options={"ftol": 1.0e-10, "maxiter": 200, "disp": False},
    )
    value = np.clip(np.asarray(result.x, dtype=np.float64), lower, upper)
    activation = nominal_activation.copy()
    activation[replace_indices] = value[:muscle_variables]
    exo = value[muscle_variables:]
    error = float(
        np.linalg.norm(muscle_map @ activation + exo_map @ exo - target_torque)
    )
    return activation, exo, bool(result.success), error


def allocate_hip_pair_impulse_replacement(
    model: mujoco.MjModel,
    muscle_map: np.ndarray,
    exo_map: np.ndarray,
    current_activation: np.ndarray,
    teacher_excitation: np.ndarray,
    excitation_lower: np.ndarray,
    excitation_upper: np.ndarray,
    exo_lower: np.ndarray,
    exo_upper: np.ndarray,
    replace_indices: np.ndarray,
    frame_skip: int,
    prevent_exo_opposition: bool = False,
    opposition_joint_rows: tuple[int, ...] = (0, 3),
) -> tuple[np.ndarray, np.ndarray, bool, float]:
    """Match mean substep torque while lowering monoarticular hip excitation."""
    replace_indices = np.asarray(replace_indices, dtype=np.int64)
    teacher_post_trace = activation_trajectory(
        model, current_activation, teacher_excitation, frame_skip
    )
    teacher_force_trace = np.concatenate(
        (current_activation[None, :], teacher_post_trace[:-1]), axis=0
    )
    teacher_mean = teacher_force_trace.mean(axis=0)
    teacher_end = teacher_post_trace[-1]
    selected_map = muscle_map[:, replace_indices]
    selected_count = int(replace_indices.size)

    excitation_high = np.minimum(
        excitation_upper[replace_indices],
        teacher_excitation[replace_indices],
    )
    lower = np.concatenate((excitation_lower[replace_indices], exo_lower))
    upper = np.concatenate((excitation_high, exo_upper))
    initial = np.concatenate(
        (
            np.clip(
                teacher_excitation[replace_indices],
                excitation_lower[replace_indices],
                excitation_high,
            ),
            np.clip(np.zeros(exo_map.shape[1]), exo_lower, exo_upper),
        )
    )

    def selected_traces(
        excitation_value: np.ndarray,
    ) -> tuple[np.ndarray, np.ndarray]:
        excitation = teacher_excitation.copy()
        excitation[replace_indices] = excitation_value
        post_trace = activation_trajectory(
            model, current_activation, excitation, frame_skip
        )[:, replace_indices]
        force_trace = np.concatenate(
            (
                current_activation[replace_indices][None, :],
                post_trace[:-1],
            ),
            axis=0,
        )
        return post_trace, force_trace

    target_mean_torque = selected_map @ teacher_mean[replace_indices]
    total_target_mean_torque = muscle_map @ teacher_mean
    scale = np.maximum(np.abs(target_mean_torque), 10.0)
    constraint_rows = independent_constraint_rows(
        np.concatenate((selected_map, exo_map), axis=1) / scale[:, None]
    )

    def full_torque_residual(value: np.ndarray) -> np.ndarray:
        _post_trace, force_trace = selected_traces(value[:selected_count])
        mean_activation = force_trace.mean(axis=0)
        torque = (
            selected_map @ mean_activation
            + exo_map @ value[selected_count:]
        )
        return torque - target_mean_torque

    def torque_constraint(value: np.ndarray) -> np.ndarray:
        return (full_torque_residual(value) / scale)[constraint_rows]

    def objective(value: np.ndarray) -> float:
        post_trace, _force_trace = selected_traces(value[:selected_count])
        exo = value[selected_count:]
        return 0.5 * float(
            np.mean(np.square(post_trace)) + 1.0e-8 * (exo @ exo)
        )

    constraints: list[dict[str, object] | LinearConstraint] = [
        {"type": "eq", "fun": torque_constraint}
    ]
    if prevent_exo_opposition and exo_map.shape[1] > 0:
        valid_rows = [
            int(row)
            for row in opposition_joint_rows
            if 0 <= int(row) < int(target_mean_torque.size)
        ]

        def direction_constraint(value: np.ndarray) -> np.ndarray:
            exo_torque = exo_map @ value[selected_count:]
            values = []
            for joint_row in valid_rows:
                target = float(total_target_mean_torque[joint_row])
                direction = 1.0 if target >= 0.0 else -1.0
                directed = direction * exo_torque[joint_row]
                values.extend((directed, abs(target) - directed))
            return np.asarray(values, dtype=np.float64)

        constraints.append({"type": "ineq", "fun": direction_constraint})

    result = minimize(
        fun=objective,
        x0=np.clip(initial, lower, upper),
        method="SLSQP",
        bounds=Bounds(lower, upper),
        constraints=constraints,
        options={"ftol": 1.0e-10, "maxiter": 200, "disp": False},
    )
    value = np.clip(np.asarray(result.x, dtype=np.float64), lower, upper)
    excitation = teacher_excitation.copy()
    excitation[replace_indices] = value[:selected_count]
    activation = activation_trajectory(
        model, current_activation, excitation, frame_skip
    )[-1]
    exo = value[selected_count:]
    error = float(np.linalg.norm(full_torque_residual(value)))
    return activation, exo, bool(result.success), error


def project_to_reachable_torque(
    muscle_map: np.ndarray,
    exo_map: np.ndarray,
    requested_torque: np.ndarray,
    activation_lower: np.ndarray,
    activation_upper: np.ndarray,
    exo_lower: np.ndarray,
    exo_upper: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, float]:
    """Project an arbitrary requested torque onto the current one-frame reachable set."""
    combined_map = np.concatenate((muscle_map, exo_map), axis=1)
    lower = np.concatenate((activation_lower, exo_lower))
    upper = np.concatenate((activation_upper, exo_upper))
    scale = np.maximum(np.abs(requested_torque), 10.0)
    result = lsq_linear(
        combined_map / scale[:, None],
        requested_torque / scale,
        bounds=(lower, upper),
        tol=1.0e-10,
        lsmr_tol=1.0e-10,
        max_iter=300,
    )
    value = np.clip(np.asarray(result.x, dtype=np.float64), lower, upper)
    projected = combined_map @ value
    error = float(np.linalg.norm(projected - requested_torque))
    muscle_count = int(muscle_map.shape[1])
    return projected, value[:muscle_count], value[muscle_count:], error


def excitation_to_action(excitation: np.ndarray, mapping: str) -> np.ndarray:
    value = np.clip(np.asarray(excitation, dtype=np.float64), 1.0e-8, 1.0 - 1.0e-8)
    if mapping in {"myosuite", "myosuite_sigmoid", "myosuite_muscle_sigmoid"}:
        action = 0.5 + np.log(value / (1.0 - value)) / 5.0
    else:
        action = 2.0 * value - 1.0
    return np.clip(action, -1.0, 1.0)


def cocontraction_nm(torque_map: np.ndarray, activation: np.ndarray) -> float:
    contribution = torque_map * activation[None, :]
    positive = np.maximum(contribution, 0.0).sum(axis=1)
    negative = np.maximum(-contribution, 0.0).sum(axis=1)
    return float(np.minimum(positive, negative).mean())


def tint_ghost_model(model: mujoco.MjModel) -> None:
    for geom_id in range(int(model.ngeom)):
        body_id = int(model.geom_bodyid[geom_id])
        body_name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_BODY, body_id) or ""
        geom_name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, geom_id) or ""
        if body_name not in {"world", "ground"} and not geom_name.startswith("terrain"):
            model.geom_rgba[geom_id] = np.asarray([0.05, 0.35, 1.0, 1.0], dtype=np.float32)
        else:
            model.geom_rgba[geom_id] = 0.0


def blend_ghost(base: np.ndarray, ghost: np.ndarray) -> np.ndarray:
    result = base.astype(np.float32)
    ghost_float = ghost.astype(np.float32)
    red, green, blue = (ghost_float[:, :, i] for i in range(3))
    mask = (blue > 35.0) & (blue > red + 22.0) & (blue > green + 8.0)
    result[mask] = 0.52 * result[mask] + 0.48 * ghost_float[mask]
    return np.clip(result, 0, 255).astype(np.uint8)


def add_label(frame: np.ndarray, label: str) -> np.ndarray:
    from PIL import Image, ImageDraw

    image = Image.fromarray(frame)
    draw = ImageDraw.Draw(image)
    draw.rectangle((8, 8, 240, 34), fill=(255, 255, 255))
    draw.text((14, 12), label, fill=(0, 0, 0))
    return np.asarray(image)


